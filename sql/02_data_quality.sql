-- OpportunityLens — 02_data_quality.sql
-- Data Quality and Integrity Audit Queries
-- ==============================================================================

USE DATABASE OPPORTUNITYLENS_DB;
USE SCHEMA APP;

-- 1. Check Total Ingested Opportunities
SELECT COUNT(*) AS TOTAL_OPPORTUNITIES
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES;

-- 2. Audit for Missing Critical Attributes
SELECT 
    COUNT_IF(TITLE IS NULL OR TRIM(TITLE) = '') AS MISSING_TITLES,
    COUNT_IF(CATEGORY IS NULL OR TRIM(CATEGORY) = '') AS MISSING_CATEGORIES,
    COUNT_IF(ORGANIZATION IS NULL OR TRIM(ORGANIZATION) = '') AS MISSING_ORGANIZATIONS,
    COUNT_IF(SOURCE_URL IS NULL OR TRIM(SOURCE_URL) = '') AS MISSING_SOURCE_URLS,
    COUNT_IF(ELIGIBILITY IS NULL OR TRIM(ELIGIBILITY) = '') AS MISSING_ELIGIBILITY
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES;

-- 3. Audit for Duplicate Opportunities by Title and Organization
SELECT 
    LOWER(TRIM(ORGANIZATION)) AS CLEAN_ORG,
    LOWER(TRIM(TITLE)) AS CLEAN_TITLE,
    COUNT(*) AS OCCURRENCES
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES
GROUP BY CLEAN_ORG, CLEAN_TITLE
HAVING COUNT(*) > 1;

-- 4. Audit URL Schemes (Ensure all start with http:// or https://)
SELECT 
    OPPORTUNITY_ID,
    TITLE,
    SOURCE_URL
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES
WHERE SOURCE_URL NOT LIKE 'http://%' 
  AND SOURCE_URL NOT LIKE 'https://%';

-- 5. Verification Status Consistency Check
SELECT 
    STATUS AS VERIFICATION_STATUS,
    COUNT(*) AS RECORD_COUNT,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 1) AS PERCENTAGE
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES
GROUP BY STATUS
ORDER BY RECORD_COUNT DESC;

-- 6. Audit Records Flagged for Review
SELECT 
    OPPORTUNITY_ID,
    TITLE,
    ORGANIZATION,
    STATUS,
    SOURCE_URL,
    VERIFIED_AT
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES
WHERE STATUS = 'NEEDS_REVIEW' OR STATUS = 'UNVERIFIED';

-- 7. Audit Data Freshness (Days Since Last Verification)
SELECT 
    OPPORTUNITY_ID,
    TITLE,
    ORGANIZATION,
    VERIFIED_AT,
    DATEDIFF(day, VERIFIED_AT, CURRENT_TIMESTAMP()) AS DAYS_SINCE_VERIFICATION
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES
ORDER BY DAYS_SINCE_VERIFICATION DESC NULLS LAST;
