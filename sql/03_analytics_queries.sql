-- ==============================================================================
-- OpportunityLens — 03_analytics_queries.sql
-- Analytical and Aggregation Queries for OPPORTUNITIES
-- ==============================================================================

USE DATABASE OPPORTUNITYLENS_DB;
USE SCHEMA APP;

-- 1. Category Distribution
SELECT 
    CATEGORY,
    COUNT(*) AS TOTAL_COUNT,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 1) AS PERCENTAGE
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES
GROUP BY CATEGORY
ORDER BY TOTAL_COUNT DESC;

-- 2. Application Status Distribution (Derived from Deadline)
SELECT 
    CASE
        WHEN DEADLINE IS NULL THEN 'Rolling / Ongoing'
        WHEN DEADLINE < CURRENT_DATE() THEN 'Closed'
        WHEN DATEDIFF(day, CURRENT_DATE(), DEADLINE) <= 7 THEN 'Closing Soon'
        ELSE 'Open'
    END AS APPLICATION_STATUS,
    COUNT(*) AS RECORD_COUNT,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 1) AS PERCENTAGE
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES
GROUP BY APPLICATION_STATUS
ORDER BY RECORD_COUNT DESC;

-- 3. Opportunities Closing in the Next 30 Days (Upcoming Deadlines)
SELECT 
    OPPORTUNITY_ID,
    TITLE,
    ORGANIZATION,
    CATEGORY,
    DEADLINE,
    DATEDIFF(day, CURRENT_DATE(), DEADLINE) AS DAYS_REMAINING,
    SOURCE_URL
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES
WHERE DEADLINE >= CURRENT_DATE()
  AND DEADLINE <= DATEADD(day, 30, CURRENT_DATE())
ORDER BY DEADLINE ASC;

-- 4. Geographic Distribution (Top Locations)
SELECT 
    LOCATION,
    COUNT(*) AS OPPORTUNITY_COUNT
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES
GROUP BY LOCATION
ORDER BY OPPORTUNITY_COUNT DESC;

-- 5. Cross-Tabulation: Category by Education Level
SELECT 
    CATEGORY,
    EDUCATION_LEVEL,
    COUNT(*) AS COUNT
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES
GROUP BY CATEGORY, EDUCATION_LEVEL
ORDER BY CATEGORY, COUNT DESC;

-- 6. Verification Status vs Application Status Matrix
SELECT 
    STATUS AS VERIFICATION_STATUS,
    CASE 
        WHEN DEADLINE IS NULL THEN 'Rolling / Ongoing'
        WHEN DEADLINE < CURRENT_DATE() THEN 'Closed'
        WHEN DATEDIFF(day, CURRENT_DATE(), DEADLINE) <= 7 THEN 'Closing Soon'
        ELSE 'Open'
    END AS APPLICATION_STATUS,
    COUNT(*) AS COUNT
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES
GROUP BY STATUS, APPLICATION_STATUS
ORDER BY STATUS, COUNT DESC;

-- 7. Data Freshness and Audit Summary
SELECT 
    COUNT(*) AS TOTAL_OPPORTUNITIES,
    COUNT(DISTINCT ORGANIZATION) AS TOTAL_ORGANIZATIONS,
    MIN(VERIFIED_AT) AS EARLIEST_VERIFIED_AT,
    MAX(VERIFIED_AT) AS MOST_RECENT_VERIFIED_AT,
    ROUND(AVG(DATEDIFF(hour, VERIFIED_AT, CURRENT_TIMESTAMP())), 1) AS AVG_HOURS_SINCE_VERIFICATION
FROM OPPORTUNITYLENS_DB.APP.OPPORTUNITIES;
